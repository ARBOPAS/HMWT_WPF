        /// <summary>Иконка по значку в начале строки; пусто, если значка нет.</summary>
        public static string IconForSymbol(string text)
        {
            if (string.IsNullOrEmpty(text)) return "";

            // Вариационный селектор (U+FE0F) невидим, но из-за него «✏️» и «✏»
            // считаются разными строками — поэтому сравниваем без него
            string trimmed = text.TrimStart().Replace("\uFE0F", "");

            foreach (var pair in Symbols)
            {
                string symbol = pair.Symbol.Replace("\uFE0F", "");
                if (trimmed.StartsWith(symbol, StringComparison.Ordinal)) return pair.Kind;
            }
            return "";
        }
