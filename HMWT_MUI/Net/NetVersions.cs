    /// <summary>Роль участника в комнате. Мастер получает скрытые броски и инструменты ДМа.</summary>
    public enum RoomRole
    {
        Player = 0,
        GameMaster = 1
    }

    /// <summary>Состояние соединения участника.</summary>
    public enum PeerState
    {
        Connecting = 0,
        Online = 1,
        Away = 2,
        Disconnected = 3
    }

    /// <summary>Типы сообщений обмена.</summary>
    public static class MsgType
    {
        // ── рукопожатие ──
        public const string Hello = "hello";              // клиент -> хост
        public const string HelloOk = "hello_ok";         // хост -> клиент
        public const string Error = "error";              // хост -> клиент

        // ── присутствие ──
        public const string Ping = "ping";
        public const string Pong = "pong";

        // ── состояние ──
        public const string Snapshot = "snapshot";        // полный снимок комнаты (до 8 человек это дешевле диффов)
        public const string PlayerUpdated = "player_updated";

        /// <summary>
        /// Игрок выходит из комнаты. Клиент шлёт это перед закрытием соединения,
        /// чтобы хост убрал его сразу, а не ждал таймаута: иначе игрок ещё
        /// секунды висел в комнате «фантомом».
        /// </summary>
        public const string Leave = "leave";

        /// <summary>
        /// Клиент просит прислать снимок заново.
        ///
        /// Нужно для периодического обновления: если другой игрок сменил аватар
        /// или здоровье, событие об этом могло не дойти, и тогда состояние
        /// запрашивается само — раз в несколько секунд.
        /// </summary>
        public const string SnapshotRequest = "snapshot_request";

        // ── фотографии ──
        //
        // Фото идёт ЧЕРЕЗ ХОСТА: у остальных порт закрыт, принять напрямую они
        // не могут. Клиент отправляет файл хосту частями, хост сохраняет его
        // у себя и рассылает остальным — так каждый видит фото другого.
        public const string PhotoChunk = "photo_chunk";   // часть файла в обе стороны

        /// <summary>
        /// Клиент просит прислать чужой аватар.
        ///
        /// Нужно при входе в комнату: в снимке есть только ПУТЬ к файлу, а самого
        /// файла у нового игрока нет. Без этого запроса чужие аватары не
        /// появлялись до тех пор, пока их владелец не сменит фото.
        /// </summary>
        public const string PhotoRequest = "photo_request";

        /// <summary>
        /// Хост просит у игрока его актуальные данные (имя, класс, здоровье и т.д.).
        /// Нужно при входе: в рукопожатии данные могли быть устаревшими, а игрок
        /// об этом не знает — у остальных он оставался со старыми.
        /// </summary>
        public const string ProfileRequest = "profile_request";

        // ── карта боя ──
        public const string MapState = "map_state";              // хост -> игрок: сцена целиком
        public const string MapRequest = "map_request";          // игрок -> хост: пришли карту
        public const string MapMove = "map_move";                // игрок -> хост: подвинул своего жетона
        public const string MapImageRequest = "map_image_request";  // игрок -> хост: пришли картинку
        public const string MapImageChunk = "map_image_chunk";      // хост -> игрок: часть картинки
        public const string MapStroke = "map_stroke";               // игрок -> хост: новый рисунок
        public const string MapStrokeErase = "map_stroke_erase";    // игрок -> хост: стёртые штрихи

        /// <summary>
        /// Хост -> игрок: жетон сдвинулся во время перетаскивания. Лёгкое
        /// сообщение вместо полной карты, иначе десять обновлений в секунду
        /// забивают канал и интерфейс.
        /// </summary>
        public const string MapTokenLive = "map_token_live";

        /// <summary>Полный путь, пройденный жетоном за перетаскивание.</summary>
        public const string MapTrail = "map_trail";

        /// <summary>Игрок создаёт/двигает/удаляет фигуру.</summary>
        public const string MapShape = "map_shape";

        /// <summary>
        /// Хост начал разведку заново (туман выключили и включили): игроки
        /// должны очистить своё локальное «разведанное» этой сцены.
        /// </summary>
        public const string MapSeenReset = "map_seen_reset";

        /// <summary>Игрок -> хост: новый разведанный сектор. Хост хранит его и рассылает остальным.</summary>
        public const string MapSeenAdd = "map_seen_add";

        /// <summary>Хост -> игрок: всё разведанное по сцене при открытии карты/входе.</summary>
        public const string MapSeenSync = "map_seen_sync";

        /// <summary>Пинг по карте: игрок/хост показал точку, её видят все в комнате.</summary>
        public const string MapPing = "map_ping";

        /// <summary>Игрок просит у хоста картинку из истории чата.</summary>
        public const string ChatImageRequest = "chat_image_request";
        public const string ChatImageResponse = "chat_image_response";

        /// <summary>Хост отвечает: такого аватара у него нет.</summary>
        public const string PhotoMissing = "photo_missing";

        // ── игровые события ──
        public const string ChatSend = "chat_send";
        public const string ChatMessage = "chat_message";
        public const string RollSend = "roll_send";
        public const string RollMessage = "roll_message";
        public const string SystemNotice = "system_notice";   // «Гром отключился» — серым в ленте
    }

